/* ===== 全局帧缓冲区（和 day5 一样的方案） ===== */
static unsigned char *g_fb_buf = NULL;

/* ---------- fb_open ---------- */
int fb_open(void)
{
    int fd = open("/dev/fb0", O_RDWR);
    if (fd < 0) {
        perror("fb_open: open /dev/fb0");
        return -1;
    }

    /* 分配全局缓冲区 */
    if (g_fb_buf == NULL) {
        g_fb_buf = (unsigned char *)calloc(1, BUF_SIZE);
        if (g_fb_buf == NULL) {
            fprintf(stderr, "fb_open: calloc failed\n");
            close(fd);
            return -1;
        }
    }
    return fd;
}

/* ---------- fb_close ---------- */
void fb_close(int fd)
{
    if (g_fb_buf) {
        free(g_fb_buf);
        g_fb_buf = NULL;
    }
    if (fd >= 0)
        close(fd);
}

/* ---------- fb_sync: 把缓冲区写入 LCD（和 day5 完全一致） ---------- */
static void fb_sync(int fd)
{
    if (fd < 0 || g_fb_buf == NULL) return;
    lseek(fd, 0, SEEK_SET);
    write(fd, g_fb_buf, BUF_SIZE);
}

/* ---------- fb_clear: 全屏填充纯色 ---------- */
void fb_clear(int fd, unsigned char b, unsigned char g, unsigned char r)
{
    if (fd < 0 || g_fb_buf == NULL) return;

    /* 完全复刻 day5 的填充方式 */
    for (int x = 0; x < SCREEN_W; x++) {
        for (int y = 0; y < SCREEN_H; y++) {
            int idx = 4 * x + 4 * SCREEN_W * y;
            g_fb_buf[idx + 0] = b;
            g_fb_buf[idx + 1] = g;
            g_fb_buf[idx + 2] = r;
            g_fb_buf[idx + 3] = 0x00;
        }
    }
    fb_sync(fd);
}

/* ---------- fb_draw_pixel: 改写缓冲区 ---------- */
void fb_draw_pixel(int fd, int x, int y, unsigned char b, unsigned char g, unsigned char r)
{
    (void)fd; /* 不写入 LCD，只改写缓冲区 */
    if (g_fb_buf == NULL) return;
    if (x < 0 || x >= SCREEN_W || y < 0 || y >= SCREEN_H) return;

    int idx = 4 * x + 4 * SCREEN_W * y;
    g_fb_buf[idx + 0] = b;
    g_fb_buf[idx + 1] = g;
    g_fb_buf[idx + 2] = r;
    g_fb_buf[idx + 3] = 0x00;
}

/* ---------- fb_draw_rect ---------- */
void fb_draw_rect(int fd, int x, int y, int w, int h,
                  unsigned char b, unsigned char g, unsigned char r, int filled)
{
    if (w <= 0 || h <= 0) return;

    int x0 = x, y0 = y;
    int x1 = x + w - 1, y1 = y + h - 1;

    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 >= SCREEN_W) x1 = SCREEN_W - 1;
    if (y1 >= SCREEN_H) y1 = SCREEN_H - 1;
    if (x0 > x1 || y0 > y1) return;

    if (filled) {
        for (int py = y0; py <= y1; py++) {
            for (int px = x0; px <= x1; px++) {
                fb_draw_pixel(fd, px, py, b, g, r);
            }
        }
    } else {
        for (int px = x0; px <= x1; px++) fb_draw_pixel(fd, px, y0, b, g, r);
        for (int px = x0; px <= x1; px++) fb_draw_pixel(fd, px, y1, b, g, r);
        for (int py = y0 + 1; py < y1; py++) fb_draw_pixel(fd, x0, py, b, g, r);
        for (int py = y0 + 1; py < y1; py++) fb_draw_pixel(fd, x1, py, b, g, r);
    }
}

/* ---------- fb_flush: 把所有缓冲区改动一次性写入 LCD ---------- */
void fb_flush(int fd)
{
    fb_sync(fd);
}

/* ---------- fb_draw_text ---------- */
void fb_draw_text(int fd, int x, int y, const char *text,
                  unsigned char b, unsigned char g, unsigned char r, int scale)
{
    if (!text) return;
    if (scale < 1) scale = 1;

    int cur_x = x, cur_y = y;
    int char_w = 8 * scale, char_h = 16 * scale;

    for (const char *c = text; *c != '\0'; ) {
        unsigned char ch = (unsigned char)*c;

        if (ch == '\n') { cur_x = x; cur_y += char_h; c++; continue; }
        if (ch == '\r') { cur_x = x; c++; continue; }

        /* UTF-8 中文检测: 3字节序列 (0xE0-0xEF 开头) */
        if (ch >= 0xE0 && ch <= 0xEF && c[1] && c[2]) {
            /* 中文用 16x16 色块表示 (可见但非真实字形) */
            int cn_w = 16 * scale;
            int cn_h = 16 * scale;
            /* 用文字颜色画实心方块代表中文 */
            for (int ry = 0; ry < cn_h; ry++) {
                for (int rx = 0; rx < cn_w; rx++) {
                    int px = cur_x + rx, py = cur_y + ry;
                    if (px >= 0 && px < SCREEN_W && py >= 0 && py < SCREEN_H)
                        fb_draw_pixel(fd, px, py, b, g, r);
                }
            }
            /* 中间画一个浅色小点标记 */
            int cx = cur_x + cn_w/2, cy = cur_y + cn_h/2;
            unsigned char lb = 255-b, lg = 255-g, lr = 255-r;
            for (int ry = -2; ry <= 2; ry++)
                for (int rx = -2; rx <= 2; rx++)
                    fb_draw_pixel(fd, cx+rx, cy+ry, lb, lg, lr);

            cur_x += cn_w;
            c += 3;  /* 跳过3字节UTF-8 */
            continue;
        }

        /* 跳过其他非ASCII字符 */
        if (ch < 32 || ch > 126) { cur_x += char_w; c++; continue; }

        const unsigned char *glyph = FONT8X16[ch - 32];
        for (int row = 0; row < 16; row++) {
            unsigned char bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    for (int sy = 0; sy < scale; sy++) {
                        for (int sx = 0; sx < scale; sx++) {
                            fb_draw_pixel(fd, cur_x + col * scale + sx,
                                          cur_y + row * scale + sy, b, g, r);
                        }
                    }
                }
            }
        }
        cur_x += char_w;
        c++;
    }
}

/* ---------- fb_draw_bmp ---------- */
void fb_draw_bmp(int fd, int x, int y, int w, int h, const char *path)
{
    if (!path) return;

    FILE *fp = fopen(path, "rb");
    if (!fp) { fprintf(stderr, "fb_draw_bmp: cannot open %s\n", path); return; }

    unsigned char file_hdr[14];
    if (fread(file_hdr, 1, 14, fp) != 14) { fclose(fp); return; }
    if (file_hdr[0] != 'B' || file_hdr[1] != 'M') { fclose(fp); return; }

    unsigned int data_offset = file_hdr[10] | (file_hdr[11] << 8) |
                               (file_hdr[12] << 16) | (file_hdr[13] << 24);

    unsigned char dib_hdr[40];
    if (fread(dib_hdr, 1, 40, fp) != 40) { fclose(fp); return; }

    int bmp_w = dib_hdr[4]  | (dib_hdr[5]  << 8) | (dib_hdr[6]  << 16) | (dib_hdr[7]  << 24);
    int bmp_h = dib_hdr[8]  | (dib_hdr[9]  << 8) | (dib_hdr[10] << 16) | (dib_hdr[11] << 24);
    int bpp   = dib_hdr[14] | (dib_hdr[15] << 8);
    int comp  = dib_hdr[16] | (dib_hdr[17] << 8) | (dib_hdr[18] << 16) | (dib_hdr[19] << 24);

    if (bmp_w <= 0 || bmp_h <= 0) { fclose(fp); return; }
    if (bpp != 24 && bpp != 32) { fclose(fp); return; }
    if (comp != 0) { fclose(fp); return; }

    int row_bytes = ((bmp_w * (bpp / 8) + 3) / 4) * 4;
    unsigned char *src_row = (unsigned char *)malloc(row_bytes);
    if (!src_row) { fclose(fp); return; }

    fseek(fp, data_offset, SEEK_SET);

    if (w <= 0) w = bmp_w;
    if (h <= 0) h = bmp_h;

    for (int dy = 0; dy < h; dy++) {
        int src_row_idx = (h - 1 - dy) * bmp_h / h;  /* BMP bottom-to-top */
        int row_offset = src_row_idx * row_bytes;
        fseek(fp, data_offset + row_offset, SEEK_SET);
        if (fread(src_row, 1, row_bytes, fp) != (size_t)row_bytes) break;

        for (int dx = 0; dx < w; dx++) {
            int src_col = dx * bmp_w / w;
            int px = x + dx, py = y + dy;
            if (px < 0 || px >= SCREEN_W || py < 0 || py >= SCREEN_H) continue;

            unsigned char blue, green, red;
            if (bpp == 24) {
                blue  = src_row[src_col * 3 + 0];
                green = src_row[src_col * 3 + 1];
                red   = src_row[src_col * 3 + 2];
            } else {
                blue  = src_row[src_col * 4 + 0];
                green = src_row[src_col * 4 + 1];
                red   = src_row[src_col * 4 + 2];
            }
            fb_draw_pixel(fd, px, py, blue, green, red);
        }
    }

    free(src_row);
    fclose(fp);
}

/* ---------- fb_get_buffer ---------- */
unsigned char* fb_get_buffer(int fd)
{
    (void)fd;
    return g_fb_buf;
}
